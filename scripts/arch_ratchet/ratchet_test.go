func fileWith(codeLines int, funcs ...funcMetrics) fileMetrics {
	return fileMetrics{codeLines: codeLines, funcs: funcs}
}

func fn(key string, lines int) funcMetrics {
	return funcMetrics{key: key, values: map[metric]int{metricLines: lines}}
}

func TestCompareFuncs(t *testing.T) {
	cases := []struct {
		name    string
		base    []funcMetrics
		head    []funcMetrics
		allowed exceptionSet
		want    []violation
	}{
		{
			name: "over-limit function grows",
			base: []funcMetrics{fn("p.F", 150)},
			head: []funcMetrics{fn("p.F", 151)},
			want: []violation{{subject: "p.F", metric: metricLines, before: 150, after: 151, limit: 100}},
		},
		{name: "over-limit function shrinks", base: []funcMetrics{fn("p.F", 150)}, head: []funcMetrics{fn("p.F", 149)}},
		{name: "function grows within the limit", base: []funcMetrics{fn("p.F", 40)}, head: []funcMetrics{fn("p.F", 100)}},
		{
			name: "function grows past the limit",
			base: []funcMetrics{fn("p.F", 90)},
			head: []funcMetrics{fn("p.F", 101)},
			want: []violation{{subject: "p.F", metric: metricLines, before: 90, after: 101, limit: 100}},
		},
		{
			name: "new over-limit function",
			head: []funcMetrics{fn("p.G", 101)},
			want: []violation{{subject: "p.G", metric: metricLines, before: 0, after: 101, limit: 100}},
		},
		{name: "over-limit function moves package", base: []funcMetrics{fn("p.F", 150)}, head: []funcMetrics{fn("q.F", 150)}},
		{
			name: "moved function grows",
			base: []funcMetrics{fn("p.F", 150)},
			head: []funcMetrics{fn("q.F", 151)},
			want: []violation{{subject: "q.F", metric: metricLines, before: 0, after: 151, limit: 100}},
		},
		{
			name: "one removed function covers only one move",
			base: []funcMetrics{fn("p.F", 150)},
			head: []funcMetrics{fn("q.F", 150), fn("q.G", 150)},
			want: []violation{{subject: "q.G", metric: metricLines, before: 0, after: 150, limit: 100}},
		},
		{
			name: "moves prefer the removed function with the same name",
			base: []funcMetrics{fn("p.A", 200), fn("p.B", 150)},
			head: []funcMetrics{fn("q.A", 150), fn("q.C", 180)},
			want: []violation{{subject: "q.C", metric: metricLines, before: 0, after: 180, limit: 100}},
		},
		{
			name:    "reviewed exception",
			base:    []funcMetrics{fn("p.F", 150)},
			head:    []funcMetrics{fn("p.F", 160)},
			allowed: exceptionSet{Exceptions: []exception{{Subject: "p.F", Metric: metricLines, Max: 160, Reason: "incident fix"}}},
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			base := map[string]fileMetrics{"a.go": fileWith(0, tc.base...)}
			head := map[string]fileMetrics{"a.go": fileWith(0, tc.head...)}
			assert.Equal(t, tc.want, compareFuncs(base, head, tc.allowed))
		})
	}
}

func TestCompareFuncsKeepsBuildTagVariantsApart(t *testing.T) {
	base := map[string]fileMetrics{
		"p/f_linux.go":  fileWith(0, fn("p.F", 150)),
		"p/f_darwin.go": fileWith(0, fn("p.F", 150)),
	}
	head := map[string]fileMetrics{
		"p/f_linux.go":  fileWith(0, fn("p.F", 160)),
		"p/f_darwin.go": fileWith(0, fn("p.F", 150)),
	}
	assert.Equal(t, []violation{{subject: "p.F@p/f_linux.go", metric: metricLines, before: 150, after: 160, limit: 100}},
		compareFuncs(base, head, exceptionSet{}))
}

