func TestCompareFilesFlagsNewAndGrowingLongFiles(t *testing.T) {
	base := map[string]fileMetrics{"old.go": fileWith(900), "shrinks.go": fileWith(900)}
	head := map[string]fileMetrics{
		"old.go":     fileWith(901),
		"shrinks.go": fileWith(800),
		"new.go":     fileWith(501),
		"small.go":   fileWith(500),
	}
	assert.Equal(t, []violation{
		{subject: "new.go", metric: metricFileLines, before: 0, after: 501, limit: limitFileLines},
		{subject: "old.go", metric: metricFileLines, before: 900, after: 901, limit: limitFileLines},
	}, compareFiles(base, head, exceptionSet{}))
}

func TestCompareTotalsIsNeutralToMovesButFlagsAdditions(t *testing.T) {
	base := map[string]fileMetrics{"a.go": {nolint: 1, modelMatching: 2}, "b.go": {}}
	moved := map[string]fileMetrics{"a.go": {}, "b.go": {nolint: 1, modelMatching: 2}}
	assert.Empty(t, compareTotals(base, moved, exceptionSet{}))

	added := map[string]fileMetrics{"a.go": {nolint: 1, modelMatching: 2}, "b.go": {nolint: 1}}
	got := compareTotals(base, added, exceptionSet{})
	require.Len(t, got, 1)
	assert.Equal(t, metricNolint, got[0].metric)
}

