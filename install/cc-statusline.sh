# ---------- release manifest verification ----------
#
# Shared by every fetched-code path: a downloaded body may replace an
# installed file only after weave_verify_manifest accepts the fetched MANIFEST
# and weave_verify_file matches the body against that MANIFEST's row. These
# helpers are duplicated verbatim in cc-statusline.sh, codex-status.sh and
# install.sh (and the copies install.sh embeds); keep them identical.
#
# They add the first openssl call to the installed statusline and Codex hook;
# before this only install.sh needed openssl. Both return 0 when verified,
# 1 when verification fails, and WEAVE_VERIFY_UNAVAILABLE (2) when openssl or
# a SHA-256 tool is missing. Callers refuse the swap on any non-zero status,
# so a machine without openssl never auto-updates (fail closed);
# WEAVE_STATUSLINE_UPDATE=0 remains the way to turn the refresh off.
WEAVE_VERIFY_UNAVAILABLE=2

# weave_verify_manifest <manifest> <sig.b64> <pubkey-pem>
# Checks the base64 RSA/SHA-256 signature in <sig.b64> over <manifest> with
# `openssl dgst -sha256 -verify`, using the PEM text in <pubkey-pem>.
weave_verify_manifest() {
  local manifest="${1:-}" sig_b64="${2:-}" pubkey_pem="${3:-}" dir out rc=1
  command -v openssl >/dev/null 2>&1 || return "$WEAVE_VERIFY_UNAVAILABLE"
  [[ -f "$manifest" && -s "$manifest" && -f "$sig_b64" && -s "$sig_b64" ]] || return 1
  [[ "$pubkey_pem" == *"-----BEGIN PUBLIC KEY-----"* ]] || return 1
  dir="$(mktemp -d "${TMPDIR:-/tmp}/weave-verify.XXXXXX")" || return 1
  if printf '%s\n' "$pubkey_pem" >"$dir/pub.pem" \
     && tr -d ' \t\r\n' <"$sig_b64" >"$dir/sig.b64" \
     && [[ -s "$dir/sig.b64" ]] \
     && openssl base64 -d -A -in "$dir/sig.b64" -out "$dir/sig" 2>/dev/null \
     && [[ -s "$dir/sig" ]]; then
    if out="$(openssl dgst -sha256 -verify "$dir/pub.pem" -signature "$dir/sig" "$manifest" 2>/dev/null)" \
       && [[ "$out" == "Verified OK" ]]; then
      rc=0
    fi
  fi
  rm -rf "$dir"
  return "$rc"
}

# weave_sha256 <file>: print the lowercase hex SHA-256 of <file>.
weave_sha256() {
  local out
  if command -v sha256sum >/dev/null 2>&1; then
    out="$(sha256sum <"$1")" || return 1
  elif command -v shasum >/dev/null 2>&1; then
    out="$(shasum -a 256 <"$1")" || return 1
  else
    return "$WEAVE_VERIFY_UNAVAILABLE"
  fi
  printf '%s\n' "${out%% *}"
}

# weave_verify_file <manifest> <path-in-manifest> <candidate>
# Succeeds only when <manifest> has exactly one well-formed row for
# <path-in-manifest> (e.g. install/cc-statusline.sh) and its digest equals the
# SHA-256 of <candidate>. Call only after weave_verify_manifest accepted
# <manifest>.
weave_verify_file() {
  local manifest="${1:-}" path_in_manifest="${2:-}" candidate="${3:-}" rows got rc
  [[ -n "$path_in_manifest" && -f "$manifest" && -f "$candidate" ]] || return 1
  rows="$(awk -v n="$path_in_manifest" 'NF == 2 && $2 == n { print $1 }' "$manifest")" || return 1
  [[ "$rows" =~ ^[0-9a-f]{64}$ ]] || return 1
  got="$(weave_sha256 "$candidate")" && rc=0 || rc=$?
  [[ "$rc" -eq 0 ]] || return "$rc"
  [[ "$got" =~ ^[0-9a-f]{64}$ && "$got" == "$rows" ]]
}

# ---------- unsigned self-hoster opt-in ----------
#
# WEAVE_STATUSLINE_TRUST_UNSIGNED=1 lets a self-hoster fork that serves its own
# copies skip the signed-manifest check, so the fork does not need a signing
# pipeline of its own. It is honored only for a source URL the user overrode
# to a host other than raw.githubusercontent.com; the default publisher always
# verifies. It provides no security property: a tampered replacement can
# remove this gate along with everything else. These helpers are duplicated
# verbatim in cc-statusline.sh, codex-status.sh and install.sh (and the copies
# install.sh embeds); keep them identical.
WEAVE_TRUST_UNSIGNED_WARNING='WEAVE_STATUSLINE_TRUST_UNSIGNED=1: skipping signature verification. This is advisory only — a tampered replacement script can remove this gate. The real trust boundary is the signed manifest on the default publisher.'

# weave_trust_unsigned <url>: succeeds when WEAVE_STATUSLINE_TRUST_UNSIGNED=1
# and <url>'s host is set and is not the default publisher.
weave_trust_unsigned() {
  [ "${WEAVE_STATUSLINE_TRUST_UNSIGNED:-}" = "1" ] || return 1
  local host="${1:-}"
  [ -n "$host" ] || return 1
  case "$host" in
    *://*) host="${host#*://}" ;;
  esac
  host="${host%%[/?#]*}"
  host="${host##*@}"
  host="${host%%:*}"
  host="$(printf '%s' "$host" | tr '[:upper:]' '[:lower:]')"
  host="${host%.}"
  [ "$host" != "raw.githubusercontent.com" ]
}

# weave_warn_trust_unsigned <url>...: prints WEAVE_TRUST_UNSIGNED_WARNING to
# stderr once when any <url> is trusted unsigned.
weave_warn_trust_unsigned() {
  local url
  for url in "$@"; do
    if weave_trust_unsigned "$url"; then
      printf '%s\n' "$WEAVE_TRUST_UNSIGNED_WARNING" >&2
      return 0
    fi
  done
  return 0
}

# ---------- pinned release source ----------
#
# The self-refresh downloads only from an immutable release tag, never from a
# mutable branch. WEAVE_RELEASE_TAG is the release this copy belongs to and is
# stamped by the release pipeline. The copy on main carries the newest signed
# release's tag, so a refresh reads that line from main to learn which tag to
# fetch, refuses any tag that is not strictly newer than its own (no
# downgrades), and then downloads MANIFEST, MANIFEST.sig.b64 and the script
# from that tag. The tag only picks where to download from; the signature over
# MANIFEST is the trust boundary. See install/RELEASE_SIGNING.md.
WEAVE_RELEASE_TAG="router-v0.2.39"
WEAVE_RELEASE_REPO_URL="https://raw.githubusercontent.com/weave-os/router"

# weave_release_tag_newer <candidate> <floor>: succeeds when both are
# router-vX.Y.Z tags and <candidate> is strictly newer than <floor>.
weave_release_tag_newer() {
  local re='^router-v([0-9]{1,9})\.([0-9]{1,9})\.([0-9]{1,9})$' cand_parts floor_parts i
  [[ "${1:-}" =~ $re ]] || return 1
  cand_parts=("${BASH_REMATCH[@]:1}")
  [[ "${2:-}" =~ $re ]] || return 1
  floor_parts=("${BASH_REMATCH[@]:1}")
  for i in 0 1 2; do
    (( 10#${cand_parts[i]} > 10#${floor_parts[i]} )) && return 0
    (( 10#${cand_parts[i]} < 10#${floor_parts[i]} )) && return 1
  done
  return 1
}

# weave_release_advertised_tag <file>: print the WEAVE_RELEASE_TAG assignment
# found in a downloaded copy of this script, if it is a well-formed tag.
weave_release_advertised_tag() {
  local tag
  [ -f "${1:-}" ] || return 1
  tag="$(sed -n 's/^WEAVE_RELEASE_TAG="\(router-v[0-9.]*\)"$/\1/p' "$1" 2>/dev/null)" || return 1
  tag="${tag%%$'\n'*}"
  [[ "$tag" =~ ^router-v[0-9]{1,9}\.[0-9]{1,9}\.[0-9]{1,9}$ ]] || return 1
  printf '%s\n' "$tag"
}

# ---------- /router-status prompt hook ----------
#
# Registered as a UserPromptSubmit hook with --prompt-hook. Every other prompt
# passes through untouched; /router-status is answered from local state and
# stopped before it reaches a model, so checking the router never spends a
# turn. The settings env (router URL and key header) is inherited by hooks, and
# the session's last statusline render is cached by the statusline below.
# The router keeps the last usage it observed on this user's own Claude/Codex
# login; the client never sends its provider token to ask for it.
weave_router_status_seats() {
  command -v curl >/dev/null 2>&1 || return 0
  local url="${ANTHROPIC_BASE_URL%/}" root header_file body header
  local forwarded='^X-Weave-(Router-Key|User-Email|User-Name):[[:space:]]*[^"\[:cntrl:]]+$'
  case "$url" in file://*) ;; *) url="$url/v1/display-settings" ;; esac
  root="${XDG_CACHE_HOME:-$HOME/.cache}/weave-router"
  mkdir -p "$root" && chmod 700 "$root" || return 0
  header_file="$(mktemp "$root/.status-headers.XXXXXX")" || return 0
  chmod 600 "$header_file"
  while IFS= read -r header; do
    [[ "$header" =~ $forwarded ]] \
      && printf 'header = "%s"\n' "$header" >>"$header_file"
  done <<<"${ANTHROPIC_CUSTOM_HEADERS:-}"
  body="$(curl -fsS --max-time 3 -K "$header_file" "$url" 2>/dev/null)"
  rm -f "$header_file"
  [ -n "$body" ] || return 0
  jq -r '
    def span: if . == 10080 then "week" elif . % 1440 == 0 then "\(. / 1440)d" elif . % 60 == 0 then "\(. / 60)h" else "\(.)m" end;
    def window($minutes; $used): if ($minutes // 0) > 0 then "\($minutes | span) \($used // 0 | floor)%" else empty end;
    .own_seats[]? | select(.provider == "claude" or .provider == "codex")
    | [window(.primary_window_minutes; .primary_used_percent), window(.secondary_window_minutes; .secondary_used_percent)] as $windows
    | select($windows | length > 0)
    | "Your \(if .provider == "claude" then "Claude" else "Codex" end) seat: \($windows | join(" · ")) (as of \(.observed_at[11:16]) UTC)"' <<<"$body" 2>/dev/null
}

weave_router_status_hook() {
  command -v jq >/dev/null 2>&1 || return 0
  local payload prompt session line="" root report scope_suffix="" seats=""
  [ "$#" -eq 0 ] || scope_suffix="$(printf ' %q' "$@")"
  payload="$(cat)"
  prompt="$(jq -r '.prompt // empty' <<<"$payload" 2>/dev/null)" || return 0
  [[ "$prompt" =~ ^[[:space:]]*/router-status[[:space:]]*$ ]] || return 0
  if [[ "${ANTHROPIC_BASE_URL:-}" == https://api.anthropic.com* ]]; then
    report="Weave Router is off: Claude Code talks to Anthropic directly. Turn it back on with /router-on."
  elif [[ -n "${ANTHROPIC_BASE_URL:-}" && "${ANTHROPIC_CUSTOM_HEADERS:-}" == *"X-Weave-Router-Key:"* ]]; then
    report="Weave Router is on: Claude Code sends requests to ${ANTHROPIC_BASE_URL}."
  elif [[ -n "${ANTHROPIC_BASE_URL:-}" ]]; then
    report="Claude Code sends requests to ${ANTHROPIC_BASE_URL}, but no Weave Router key is set. Repair it with: npx @weave-os/router update --claude${scope_suffix}"
  else
    report="Weave Router is off: Claude Code talks to Anthropic directly. Turn it back on with /router-on."
  fi
  session="$(jq -r '.session_id // empty' <<<"$payload" 2>/dev/null)" || session=""
  root="${XDG_CACHE_HOME:-$HOME/.cache}/weave-router/claude-status"
  if [[ "$session" =~ ^[A-Za-z0-9._-]{1,128}$ && -f "$root/$session.line" ]]; then
    line="$(head -c 512 "$root/$session.line" | head -n 1)"
  fi
  if [[ -n "${ANTHROPIC_BASE_URL:-}" && "${ANTHROPIC_CUSTOM_HEADERS:-}" == *"X-Weave-Router-Key:"* ]]; then
    seats="$(weave_router_status_seats)"
  fi
  [ -z "$seats" ] || report="$report"$'\n'"$seats"
  if [[ -n "$line" ]]; then
    report="$report"$'\n'"This session: $line"
  else
    report="$report"$'\n'"No routed turn yet in this session."
  fi
  report="$report"$'\n'"Full check (key, login, endpoint): npx @weave-os/router status --claude${scope_suffix}"
  jq -n --arg reason "$report" '{continue: false, stopReason: $reason, suppressOutput: true}'
}
if [ "${1:-}" = "--prompt-hook" ]; then
  shift
  weave_router_status_hook "$@" || true
  exit 0
fi

# ---------- background self-refresh ----------
#
# Once every WEAVE_STATUSLINE_UPDATE_INTERVAL_DAYS (default 7), check for a
# newer signed release of this script (see "pinned release source" above) and
# swap it in atomically once its signed MANIFEST verifies. Runs in a forked subshell so the current Claude turn never
# blocks; the next turn picks up the new version. Applies to both user-scope
# (~/.weave/cc-statusline.sh) and project-scope (<repo>/.claude/cc-statusline.sh)
# installs — project teammates rate-limit independently because the stamp
# lives in their per-user cache dir, and on no-content-change days we skip
# the mv entirely so the repo working tree stays clean. When upstream does
# change, the first teammate's commit propagates the new version to the rest.
# A pricing-table miss also triggers a refresh off-schedule — see
# weave_refresh_on_price_miss below.
#
# Opt out entirely with `export WEAVE_STATUSLINE_UPDATE=0`. Self-hosters who
# fork can point `WEAVE_STATUSLINE_URL=...` at their own copy; MANIFEST and
# MANIFEST.sig.b64 are then read from the same directory and must still verify
# under the embedded key, unless WEAVE_STATUSLINE_TRUST_UNSIGNED=1 and that URL
# is on another host (see "unsigned self-hoster opt-in" above), in which case
# only the shape checks apply.
#
# $1 is an optional stamp suffix, so a caller refreshing for a reason other than
# "the interval elapsed" rate-limits on its own clock rather than sharing the
# periodic check's budget. $2=1 drops the stamp again if the download fails, for
# callers recovering from a known-bad state where waiting out the full interval
# on a transient network error is worse than retrying next turn.
#
# Fetched-code surface 1 (inventory in install.sh, "uninstall delegation"):
# the downloaded body replaces this script and runs on the next turn. It is
# swapped in only after weave_verify_manifest accepts the fetched MANIFEST and
# weave_verify_file matches the body to its row; on any failure the installed
# copy is left as it is.
weave_self_refresh() {
  local stamp_suffix="${1:-}"
  local retry_on_fail="${2:-0}"

  [ "${WEAVE_STATUSLINE_UPDATE:-1}" = "0" ] && return 0
  command -v curl >/dev/null 2>&1 || return 0

  local self="${BASH_SOURCE[0]:-$0}"
  [ -f "$self" ] && [ -w "$self" ] || return 0

  local interval_days="${WEAVE_STATUSLINE_UPDATE_INTERVAL_DAYS:-7}"
  local interval_seconds=$(( interval_days * 86400 ))

  # Stamp lives in the per-user cache dir, keyed by absolute script path so
  # multiple repos (and the user-scope copy) rate-limit independently and no
  # stray file ever lands inside a repo working tree.
  local cache_dir="${XDG_CACHE_HOME:-$HOME/.cache}/weave-router"
  mkdir -p "$cache_dir" 2>/dev/null || return 0
  local script_slug
  script_slug="$(printf '%s' "$self" | tr -c 'A-Za-z0-9._-' '_')"
  local stamp="$cache_dir/checked-at${script_slug}${stamp_suffix}"

  local now stamp_mtime
  now="$(date +%s 2>/dev/null)" || return 0
  if [ -f "$stamp" ]; then
    # Try GNU `stat -c %Y` first; on macOS (BSD stat) -c isn't recognized
    # and exits non-zero, so we fall through to `stat -f %m`. The reverse
    # order is broken: GNU `stat -f` is `--file-system`, which silently
    # succeeds with multi-line filesystem info instead of failing, leaving
    # $stamp_mtime as garbage and disabling the rate-limit check entirely.
    stamp_mtime="$(stat -c %Y "$stamp" 2>/dev/null || stat -f %m "$stamp" 2>/dev/null)" || stamp_mtime=0
  else
    stamp_mtime=0
  fi
  if [ -n "${stamp_mtime:-}" ] && [ "$stamp_mtime" -gt 0 ] \
     && [ $(( now - stamp_mtime )) -lt "$interval_seconds" ]; then
    return 0
  fi

  # Touch the stamp BEFORE forking so concurrent statusline invocations
  # (Claude calls us on every turn) don't all kick off downloads.
  : > "$stamp" 2>/dev/null || return 0

  # $$ alone is not unique: two calls can run in one invocation (the periodic
  # check and a pricing-miss retry both fire on a cold cache) and would then
  # download into the same paths and mv over each other, installing a truncated
  # script that can never self-heal. The stamp suffix is the right key — it is
  # what makes two callers mutually exclusive in the first place, so callers
  # that could overlap necessarily have different suffixes.
  local tmp="${self}.tmp.$$${stamp_suffix}"
  (
    # Detach stdin so curl can't accidentally consume it, and silence all
    # output so nothing leaks into the client's display.
    exec </dev/null
    local base url outcome=fail unsigned=0 tag="" body_tag=""
    if [ -n "${WEAVE_STATUSLINE_URL:-}" ]; then
      url="$WEAVE_STATUSLINE_URL"
      base="${url%/*}"
      weave_trust_unsigned "$url" && unsigned=1
    else
      base=""
      if curl -fsSL --max-time 15 "$WEAVE_RELEASE_REPO_URL/main/install/cc-statusline.sh" -o "$tmp.channel" 2>/dev/null; then
        tag="$(weave_release_advertised_tag "$tmp.channel")" || tag=""
        if weave_release_tag_newer "$tag" "$WEAVE_RELEASE_TAG"; then
          base="$WEAVE_RELEASE_REPO_URL/$tag/install"
        else
          outcome=current
        fi
      fi
      rm -f "$tmp.channel"
      url="$base/cc-statusline.sh"
    fi
    # Verify before anything touches $self: the MANIFEST signature under the
    # embedded key, then this body's SHA-256 against its MANIFEST row. The
    # signature does not name a release, so the body's own WEAVE_RELEASE_TAG
    # must be newer than this copy's and, when fetched from a tag, equal it; an
    # older signed release replayed under a newer name or URL is refused. The shape checks stay as a second line of defence, and are
    # the only check for a source trusted unsigned. A body that downloaded but
    # failed a check is "rejected", not "fail": retrying it next turn would
    # fetch the same bytes again.
    if [ "$unsigned" = "1" ]; then
      curl -fsSL --max-time 15 "$url" -o "$tmp" 2>/dev/null && outcome=fetched
    elif [ -n "$base" ] \
       && curl -fsSL --max-time 15 "$base/MANIFEST" -o "$tmp.MANIFEST" 2>/dev/null \
       && curl -fsSL --max-time 15 "$base/MANIFEST.sig.b64" -o "$tmp.MANIFEST.sig.b64" 2>/dev/null \
       && curl -fsSL --max-time 15 "$url" -o "$tmp" 2>/dev/null; then
      outcome=rejected
      if weave_verify_manifest "$tmp.MANIFEST" "$tmp.MANIFEST.sig.b64" "$WEAVE_RELEASE_PUBKEY_PEM" \
         && weave_verify_file "$tmp.MANIFEST" "install/cc-statusline.sh" "$tmp" \
         && body_tag="$(weave_release_advertised_tag "$tmp")" \
         && weave_release_tag_newer "$body_tag" "$WEAVE_RELEASE_TAG" \
         && { [ -z "$tag" ] || [ "$body_tag" = "$tag" ]; }; then
        outcome=fetched
      fi
    fi
    if [ "$outcome" = "fetched" ]; then
      if [ -s "$tmp" ] \
         && head -n 1 "$tmp" | grep -q '^#!.*bash' \
         && [ "$(wc -c <"$tmp")" -ge 1024 ]; then
        outcome=verified
      else
        outcome=rejected
      fi
    fi
    rm -f "$tmp.MANIFEST" "$tmp.MANIFEST.sig.b64"
    if [ "$outcome" = "verified" ]; then
      # No-op when the download matches what's already on disk — keeps git
      # status clean for project-scope teammates during a routine refresh.
      if cmp -s "$tmp" "$self"; then
        rm -f "$tmp"
      else
        chmod +x "$tmp" 2>/dev/null || true
        mv "$tmp" "$self" 2>/dev/null || rm -f "$tmp"
      fi
    else
      rm -f "$tmp"
      # A download that failed shouldn't spend the caller's whole interval;
      # drop the stamp so the next turn can try again. Being on the newest
      # release already, or a rejected body, is not a transient failure.
      if [ "$outcome" = "fail" ] && [ "$retry_on_fail" = "1" ]; then
        rm -f "$stamp"
      fi
    fi
  ) >/dev/null 2>&1 &
  disown 2>/dev/null || true
  return 0
}
[ "${WEAVE_STATUSLINE_UPDATE:-1}" = "0" ] \
  || weave_warn_trust_unsigned "${WEAVE_STATUSLINE_URL:-}" "${WEAVE_COMMANDS_URL_BASE:-}"
weave_self_refresh 2>/dev/null || true

# ---------- background slash-command refresh ----------
#
# The /force-model, /router-* … wrappers under <install>/.claude/commands/ are
# written once at install time and then never touched again, so a user who
# doesn't re-run the installer keeps whatever set shipped that day. This script
# is the only thing Claude Code invokes on every turn, so it doubles as the
# refresh point for them: same rate limit, same detached fork, same
# content-diff no-op as the self-refresh above.
#
# Never clobber a wrapper the user edited. The only way to tell an edit from a
# stale copy is to remember what we last downloaded, so each canonical file is
# cached (unrendered) per install under the user cache dir and a wrapper is
# replaced only when its bytes still match that baseline. With no baseline yet
# we can't prove anything, so the first run only seeds the cache and a swap can
# happen from the next one on.
#
# Every downloaded body must match its row in a MANIFEST whose signature
# verifies under the embedded release key (see "release manifest verification"
# above). MANIFEST and MANIFEST.sig.b64 are fetched once per refresh cycle; if
# either fails to download or verify, the cycle touches neither the baseline
# cache nor any wrapper. A body that does not match its row is skipped and its
# baseline is left as it is.
#
# A baseline written before this check existed (by install.sh, or by an older
# statusline that installed unverified downloads) can't be trusted as the
# "what we shipped" reference. The sentinel $baseline_dir/.manifest-seeded
# marks a cache seeded under the manifest. While it is absent, the first
# refresh whose MANIFEST verifies re-seeds once: each verified body becomes
# the baseline, an installed wrapper Router owns (in-body marker, a sidecar
# recording its exact body, or a body equal to the old baseline) that differs
# from it is replaced with it, and the sentinel is written. A wrapper
# whose body could not be fetched or verified in that cycle has its untrusted
# baseline removed, so it can only be refreshed against a verified one later.
# A marker-carrying wrapper edited before upgrading is therefore reset once on
# the first post-upgrade refresh; from then on the baseline comparison
# preserves local edits as before.
#
# Never touch a wrapper git tracks either. A project-scope install writes the
# wrappers into the repo's own .claude/commands/, and unlike cc-statusline.sh
# the installer does not gitignore them — so an unattended weekly rewrite would
# surface as unexplained dirty files (and could ride along in someone's commit).
# Only the installer changes tracked files, and only when a human runs it.
#
# Opt out with WEAVE_COMMANDS_UPDATE=0 (WEAVE_STATUSLINE_UPDATE=0 disables this
# too, along with every other network path here). Wrappers come from this
# copy's own release tag (WEAVE_RELEASE_TAG), never a mutable branch; the
# self-refresh moves the tag forward. Self-hosters who fork can point
# WEAVE_COMMANDS_URL_BASE=... at their own commands/ directory; MANIFEST and
# MANIFEST.sig.b64 are then read from its parent directory and must still
# verify under the embedded key. With WEAVE_STATUSLINE_TRUST_UNSIGNED=1 and
# that base on another host, bodies are admitted on the `---` and baseline
# checks alone; such a cycle never re-seeds or writes the sentinel, so a later
# return to a signed source still re-seeds once.

# weave_command_tracked_by_git returns 0 when $1 is a file git tracks. Used to
# leave repo-committed wrappers alone; no git (or no repo) means untracked.
weave_command_tracked_by_git() {
  command -v git >/dev/null 2>&1 || return 1
  git -C "$(dirname "$1")" ls-files --error-unmatch -- "$1" >/dev/null 2>&1
}

# weave_installed_command_names lists the wrappers this install may refresh.
# The statusline ships standalone (no registry.sh beside it), so the installed
# set — itself written from the registry — is the only source of truth here.
#
# Files written before ownership markers existed carry none, so matching on the
# marker alone would freeze every pre-marker install out of refreshes forever.
# List every wrapper instead and let the baseline comparison below decide: a
# file is replaced only when its bytes still match the last canonical copy, so
# a user-authored command is never touched whether or not it carries a marker.
weave_installed_command_names() {
  local dir="$1" file
  for file in "$dir"/*.md; do
    [ -f "$file" ] || continue
    printf '%s\n' "$(basename "$file" .md)"
  done
}

# weave_render_command prints $1 with the installer's {{SCOPE}} placeholder
# replaced by $2, matching how install_slash_commands writes the same file.
# Trailing newlines are stripped on both sides of every comparison below.
weave_render_command() {
  local body
  body="$(cat "$1" 2>/dev/null)" || return 1
  printf '%s' "${body//\{\{SCOPE\}\}/$2}"
}

# Fetched-code surface 2 (inventory in install.sh, "uninstall delegation"):
# downloaded commands/*.md bodies overwrite installed wrappers that Claude Code
# runs as prompts. A body is admitted only after weave_verify_manifest accepts
# the fetched MANIFEST and weave_verify_file matches the body to its
# install/commands/<name>.md row; the `---` first line and the baseline
# comparison stay as further checks.
weave_sync_commands() {
  [ "${WEAVE_STATUSLINE_UPDATE:-1}" = "0" ] && return 0
  [ "${WEAVE_COMMANDS_UPDATE:-1}" = "0" ] && return 0
  command -v curl >/dev/null 2>&1 || return 0

  local self="${BASH_SOURCE[0]:-$0}" self_dir cmd_dir
  self_dir="$(cd "$(dirname "$self")" 2>/dev/null && pwd -P)" || return 0
  # User scope installs this script at <base>/.weave/, project and --dir at
  # <base>/.claude/. Claude Code reads commands from <base>/.claude/commands in
  # both layouts.
  case "${self_dir##*/}" in
    .weave)  cmd_dir="${self_dir%/*}/.claude/commands" ;;
    .claude) cmd_dir="$self_dir/commands" ;;
    *)       return 0 ;;
  esac
  [ -d "$cmd_dir" ] && [ -w "$cmd_dir" ] || return 0

  local cache_dir="${XDG_CACHE_HOME:-$HOME/.cache}/weave-router"
  local dir_slug
  dir_slug="$(printf '%s' "$cmd_dir" | tr -c 'A-Za-z0-9._-' '_')"
  # Baseline is keyed by install, not shared: two installs refresh on their own
  # clocks, and a shared baseline updated by one would make the other's still-
  # canonical wrappers look user-edited and freeze them forever.
  local baseline_dir="$cache_dir/commands${dir_slug}"
  local stamp="$cache_dir/checked-at${dir_slug}.commands"
  mkdir -p "$baseline_dir" 2>/dev/null || return 0

  local interval_days="${WEAVE_STATUSLINE_UPDATE_INTERVAL_DAYS:-7}"
  local now stamp_mtime
  now="$(date +%s 2>/dev/null)" || return 0
  if [ -f "$stamp" ]; then
    stamp_mtime="$(stat -c %Y "$stamp" 2>/dev/null || stat -f %m "$stamp" 2>/dev/null)" || stamp_mtime=0
  else
    stamp_mtime=0
  fi
  if [ -n "${stamp_mtime:-}" ] && [ "$stamp_mtime" -gt 0 ] \
     && [ $(( now - stamp_mtime )) -lt $(( interval_days * 86400 )) ]; then
    return 0
  fi
  # Stamp before forking, same as the self-refresh: Claude Code calls us on
  # every turn and concurrent invocations must not all start downloading.
  : > "$stamp" 2>/dev/null || return 0

  # router-off/on/status bake this install's scope selector into their npx
  # line (upstream carries {{SCOPE}} there). Recover it from the installed copy
  # so a project or --dir install keeps toggling its own config; when it can't
  # be recovered those three are skipped rather than rewritten to point at the
  # user-scope install.
  local scope_args="" scope_known="false" off="$cmd_dir/router-off.md"
  # Backticks are literal Markdown delimiters.
  # shellcheck disable=SC2016
  if [ -f "$off" ] && grep -Eq '^`npx @(workweave/router|weave-os/router) off --claude.*`$' "$off" 2>/dev/null; then
    scope_known="true"
    # Backticks are literal Markdown delimiters.
    # shellcheck disable=SC2016
    scope_args="$(sed -En 's#^`npx @(workweave/router|weave-os/router) off --claude(.*)`$#\2#p' "$off" | head -n 1)"
    # The installed copy is local and unverified, so it may only name this
    # install: a scope flag, or the --dir selector install_slash_commands
    # writes for the directory holding .claude/commands. Any other text would
    # be copied into verified wrappers.
    local install_base="${self_dir%/*}" logical_base
    logical_base="$(cd "$(dirname "$self")" 2>/dev/null && pwd)" || logical_base=""
    logical_base="${logical_base%/*}"
    case "$scope_args" in
      "" | " --scope project" | " --dir $(printf '%q' "$install_base")" | " --dir $(printf '%q' "$logical_base")") ;;
      *) scope_args="" scope_known="false" ;;
    esac
  fi

  local url_base="${WEAVE_COMMANDS_URL_BASE:-$WEAVE_RELEASE_REPO_URL/$WEAVE_RELEASE_TAG/install/commands}"
  url_base="${url_base%/}"
  # MANIFEST sits in the parent of the wrapper directory; a wrapper directory
  # at the host root keeps the authority and uses the root.
  local manifest_base="$url_base" url_path="${url_base#*://}"
  case "$url_path" in
    */*) manifest_base="${url_base%/*}" ;;
  esac
  local sentinel="$baseline_dir/.manifest-seeded"
  local name installed raw prev tmp new_body prev_body installed_body owned
  local manifest="$baseline_dir/.MANIFEST.tmp.$$" seeding="false" unsigned="false"
  if [ -n "${WEAVE_COMMANDS_URL_BASE:-}" ] && weave_trust_unsigned "$url_base"; then
    unsigned="true"
  fi
  [ -f "$sentinel" ] || [ "$unsigned" = "true" ] || seeding="true"
  (
    # Detach stdin (CC pipes JSON to us) so curl can't consume it, and silence
    # everything so no output leaks into the statusline.
    exec </dev/null
    trap 'rm -f "$manifest" "$manifest.sig.b64"' EXIT
    if [ "$unsigned" != "true" ]; then
      curl -fsSL --max-time 15 "$manifest_base/MANIFEST" -o "$manifest" 2>/dev/null || exit 0
      curl -fsSL --max-time 15 "$manifest_base/MANIFEST.sig.b64" -o "$manifest.sig.b64" 2>/dev/null || exit 0
      weave_verify_manifest "$manifest" "$manifest.sig.b64" "$WEAVE_RELEASE_PUBKEY_PEM" || exit 0
    fi
    while IFS= read -r name; do
      installed="$cmd_dir/$name.md"
      # Only ever refresh a wrapper that is already installed: a missing one
      # was uninstalled or deliberately deleted, and resurrecting it would be
      # a surprise. A symlink is user-owned; leave it alone. A git-tracked
      # wrapper belongs to the repo — rewriting it would dirty a working tree
      # nobody asked us to touch.
      [ -f "$installed" ] || continue
      [ -L "$installed" ] && continue
      weave_command_tracked_by_git "$installed" && continue

      raw="$baseline_dir/$name.md.tmp.$$"
      prev="$baseline_dir/$name.md"
      # Signed-manifest digest first, then the shape check: every wrapper opens
      # with YAML front matter, so a 404 page or a truncated body can never be
      # installed as a command. On any failure the baseline stays as it is,
      # except while re-seeding, when the untrusted one is dropped.
      if ! curl -fsSL --max-time 15 "$url_base/$name.md" -o "$raw" 2>/dev/null \
         || { [ "$unsigned" != "true" ] \
              && ! weave_verify_file "$manifest" "install/commands/$name.md" "$raw"; } \
         || [ ! -s "$raw" ] || [ "$(head -n 1 "$raw")" != "---" ]; then
        rm -f "$raw"
        [ "$seeding" = "true" ] && rm -f "$prev"
        continue
      fi

      if grep -q '{{SCOPE}}' "$raw" && [ "$scope_known" != "true" ]; then
        mv "$raw" "$prev" 2>/dev/null || rm -f "$raw"
        continue
      fi

      if [ -f "$prev" ] || [ "$seeding" = "true" ]; then
        new_body="$(weave_render_command "$raw" "$scope_args")"
        installed_body="$(sed '/^<!-- weave-router managed command: .* -->$/d' "$installed" 2>/dev/null)" || installed_body=""
        owned="true"
        if [ "$seeding" = "true" ]; then
          # The re-seed may only replace a wrapper Router owns: one carrying the
          # in-body marker, a sidecar that still records its exact body, or a
          # body equal to the old baseline (a pre-marker install). A verified download proves
          # where the replacement came from, not who owns the destination.
          ownership_file="$installed.weave-router"
          if grep -Fqx "<!-- weave-router managed command: $name -->" "$installed" 2>/dev/null \
             || { [ -f "$ownership_file" ] && [ ! -L "$ownership_file" ] \
                  && [ "$(sed -n '1p' "$ownership_file" 2>/dev/null)" = "weave-router managed command: $name" ] \
                  && [ "$(sed '1d' "$ownership_file" 2>/dev/null)" = "$(cat "$installed" 2>/dev/null)" ]; } \
             || { [ -f "$prev" ] && [ "$(weave_render_command "$prev" "$scope_args")" = "$installed_body" ]; }; then
            prev_body="$installed_body"
          else
            owned="false"
          fi
        else
          prev_body="$(weave_render_command "$prev" "$scope_args")"
        fi
        if [ "$owned" = "true" ] && [ "$prev_body" = "$installed_body" ] \
           && [ "$new_body" != "$installed_body" ]; then
          tmp="$installed.tmp.$$"
          if printf '%s\n' "$new_body" >"$tmp" 2>/dev/null; then
            mv "$tmp" "$installed" 2>/dev/null || rm -f "$tmp"
            ownership_file="$installed.weave-router"
            if [ ! -L "$ownership_file" ]; then
              printf 'weave-router managed command: %s\n%s\n' "$name" "$new_body" \
                >"$ownership_file" 2>/dev/null || true
            fi
          else
            rm -f "$tmp"
          fi
        fi
      fi
      mv "$raw" "$prev" 2>/dev/null || rm -f "$raw"
    done <<EOF
$(weave_installed_command_names "$cmd_dir")
EOF
    [ "$seeding" = "true" ] && : >"$sentinel" 2>/dev/null
    true
  ) >/dev/null 2>&1 &
  disown 2>/dev/null || true
  return 0
}
weave_sync_commands 2>/dev/null || true

# ---------- org "hide terminal surfaces" gate ----------
#
# When the org has hidden the router's terminal surfaces, the statusline
# renders nothing: this prints no output and exits 0, leaving the slot blank.
# The setting comes from GET /v1/display-settings with the install's own
# router key, but the foreground path NEVER touches the network: it decides
# solely from a per-install cache file (TTL WEAVE_DISPLAY_SETTINGS_TTL_SECONDS,
# default 1h), and a missing or stale cache fails open — the statusline
# renders normally. When the cache is missing or stale a detached background
# refresh re-fetches the setting and rewrites the cache atomically, so the
# next turn picks up the fresh value; a refresh failure simply leaves the
# cache stale, which keeps failing open rather than pinning the gate closed.
#
# Claude Code runs the statusline every turn, so several invocations can see a
# stale cache at once. Letting each fetch independently is not safe: the
# responses can land out of order, and the loser's mv would replace a newer
# setting with an older one AND stamp it fresh, pinning the gate on a stale
# value for a full TTL. Refreshes are therefore serialized per cache key on a
# directory mutex (flock is absent on macOS), held across both
# the fetch and the write. A refresh that finds the mutex held exits rather
# than queueing — the in-flight one is at least as fresh as anything it would
# fetch, so waiting only to overwrite it is the bug. The one path that is not
# strictly exclusive is reclaiming a lock whose holder died; see below.
weave_hidden_gate() {
  command -v curl >/dev/null 2>&1 || return 1
  command -v jq >/dev/null 2>&1 || return 1

  local cache_dir="${XDG_CACHE_HOME:-$HOME/.cache}/weave-router"
  mkdir -p "$cache_dir" 2>/dev/null || return 1
  local self="${BASH_SOURCE[0]:-$0}"
  local script_slug
  script_slug="$(printf '%s' "$self" | tr -c 'A-Za-z0-9._-' '_')"
  local cache="$cache_dir/display-settings${script_slug}"
  local ttl="${WEAVE_DISPLAY_SETTINGS_TTL_SECONDS:-3600}"

  local grace="${WEAVE_DISPLAY_SETTINGS_HIDDEN_GRACE_SECONDS:-604800}"
  local now mtime fresh="false" stale_hidden="false"
  now="$(date +%s 2>/dev/null)" || now=0

  # Linked plans that need a fresh login. Only a refresh within the TTL is
  # trusted: an older list may name a plan that has since recovered.
  weave_disconnected_plans=""
  if [ -f "$cache.plans" ]; then
    mtime="$(stat -c %Y "$cache.plans" 2>/dev/null || stat -f %m "$cache.plans" 2>/dev/null)" || mtime=0
    if [ "$mtime" -gt 0 ] && [ $(( now - mtime )) -lt "$ttl" ]; then
      weave_disconnected_plans="$(cat "$cache.plans" 2>/dev/null)"
    fi
  fi
  if [ -f "$cache" ]; then
    mtime="$(stat -c %Y "$cache" 2>/dev/null || stat -f %m "$cache" 2>/dev/null)" || mtime=0
    if [ -n "${mtime:-}" ] && [ "$mtime" -gt 0 ] && [ $(( now - mtime )) -lt "$ttl" ]; then
      fresh="true"
    elif [ -n "${mtime:-}" ] && [ "$mtime" -gt 0 ] && [ $(( now - mtime )) -lt "$grace" ] \
      && [ "$(cat "$cache" 2>/dev/null)" = "1" ]; then
      stale_hidden="true"
    fi
  fi

  # Foreground decision: a fresh cache decides. A hidden cache past the TTL
  # stays hidden for the grace period while it refreshes, so an hourly expiry
  # never flashes routing details to someone who must not see them. Anything
  # else renders normally so an unreachable router cannot wedge it blank.
  if [ "$fresh" = "true" ]; then
    [ "$(cat "$cache" 2>/dev/null)" = "1" ]
    return
  fi

  # Background refresh for the next invocation. Resolve the router base URL
  # and key inside the subshell from the Claude Code settings the installer
  # wrote: project/--dir installs put both under <base>/.claude alongside
  # this script (key in settings.local.json), while a user-scope install
  # lives under ~/.weave and reads ~/.claude. Resolve relative to the
  # script's own location, falling back to user scope, so a project install
  # never reads (or leaks) the user-scope key. ANTHROPIC_BASE_URL and
  # WEAVE_ROUTER_BASE_URL may also be set in the environment. A file:// base
  # URL is the offline/test seam: curl reads it as the response body
  # directly, so the endpoint path is meaningless for it; real router URLs
  # (https) get /v1/display-settings appended.
  (
    exec </dev/null

    # Take the per-cache-key mutex, or bail. Old locks are reclaimed so a
    # crashed holder cannot block refreshes forever. Releasing from a trap
    # covers every exit path below.
    lock="$cache.lock"
    if ! mkdir "$lock" 2>/dev/null; then
      lock_mtime="$(stat -c %Y "$lock" 2>/dev/null || stat -f %m "$lock" 2>/dev/null)" || lock_mtime=0
      lock_now="$(date +%s 2>/dev/null)" || lock_now=0
      if [ "${lock_mtime:-0}" -le 0 ] || [ $(( lock_now - lock_mtime )) -le 30 ]; then
        exit 0
      fi
      # Reclaiming an abandoned lock must not be delete-then-recreate. With
      # `rm -rf` + `mkdir`, refreshers that all see the same stale lock each
      # delete the next one's freshly created directory, so many end up holding
      # it at once (measured at 50 claimants: 4-11 concurrent holders) and their
      # writes can land out of order. Renaming is atomic, so only one racer can
      # move a given directory aside and the losers exit instead of clobbering
      # the winner (same measurement: 1-2). It is not a perfect mutex — a
      # straggler can still reclaim the new lock a winner just created, since
      # nothing distinguishes it from the stale one — but real refreshes arrive
      # one per turn rather than 50 at once, and the staleness threshold below
      # is what bounds the rest.
      dead="$lock.dead.$$"
      mv "$lock" "$dead" 2>/dev/null || exit 0
      rm -rf "$dead" 2>/dev/null
      mkdir "$lock" 2>/dev/null || exit 0
    fi
    # Some mkdir implementations return success to both racing creators.
    # Shell noclobber supplies the exclusive claim independently of mkdir.
    (set -C; : > "$lock/owner") 2>/dev/null || exit 0
    trap 'rm -f "$lock/owner"; rmdir "$lock" 2>/dev/null' EXIT

    self_dir="$(cd "$(dirname "$self")" 2>/dev/null && pwd)"
    settings_base="$HOME"
    case "$self_dir" in
      */.claude) settings_base="${self_dir%/.claude}" ;;
    esac
    settings="$settings_base/.claude/settings.json"
    local_settings="$settings_base/.claude/settings.local.json"
    base_url="${WEAVE_ROUTER_BASE_URL:-${ANTHROPIC_BASE_URL:-}}"
    key="${WEAVE_ROUTER_KEY:-}"
    if [ -z "$key" ] && [ -f "$settings" ]; then
      key="$(jq -r '.env.ANTHROPIC_CUSTOM_HEADERS // "" | split("\n")[] | select(startswith("X-Weave-Router-Key:")) | sub("^X-Weave-Router-Key:[[:space:]]*";"")' "$settings" 2>/dev/null | head -n1)"
    fi
    if [ -z "$key" ] && [ -f "$local_settings" ]; then
      key="$(jq -r '.env.ANTHROPIC_CUSTOM_HEADERS // "" | split("\n")[] | select(startswith("X-Weave-Router-Key:")) | sub("^X-Weave-Router-Key:[[:space:]]*";"")' "$local_settings" 2>/dev/null | head -n1)"
    fi
    if [ -z "$key" ] && [ -n "${ANTHROPIC_CUSTOM_HEADERS:-}" ]; then
      key="$(printf '%s\n' "$ANTHROPIC_CUSTOM_HEADERS" | sed -n 's/^X-Weave-Router-Key:[[:space:]]*\([A-Za-z0-9_-]*\)[[:space:]]*$/\1/p' | head -n1)"
    fi
    if [ -z "$base_url" ] && [ -f "$settings" ]; then
      base_url="$(jq -r '.env.ANTHROPIC_BASE_URL // empty' "$settings" 2>/dev/null)"
    fi
    [ -n "$base_url" ] && [ -n "$key" ] || exit 0
    url="${base_url%/}"
    case "$url" in
      file://*) ;;
      *) url="$url/v1/display-settings" ;;
    esac
    header_file="$(mktemp "$cache_dir/.headers.XXXXXX")" || exit 0
    chmod 600 "$header_file"
    printf 'header = "X-Weave-Router-Key: %s"\n' "$key" >"$header_file"
    custom_headers="${ANTHROPIC_CUSTOM_HEADERS:-}"
    for f in "$settings" "$local_settings"; do
      [ -n "$custom_headers" ] || [ ! -f "$f" ] || custom_headers="$(jq -r '.env.ANTHROPIC_CUSTOM_HEADERS // ""' "$f" 2>/dev/null)"
    done
    printf '%s\n' "$custom_headers" | grep -E '^X-Weave-User-(Email|Name):[[:space:]]*[A-Za-z0-9@._+ -]+$' \
      | sed 's/^\(.*\)$/header = "\1"/' >>"$header_file" 2>/dev/null || true
    if ! body="$(curl -fsS --max-time 5 -K "$header_file" "$url" 2>/dev/null)"; then
      rm -f "$header_file"
      exit 0
    fi
    rm -f "$header_file"
    hidden="$(printf '%s' "$body" | jq -r '.hide_terminal_surfaces // false' 2>/dev/null)"
    tmp="$cache.tmp.$$"
    if [ "$hidden" = "true" ]; then
      printf '1' >"$tmp" 2>/dev/null && mv "$tmp" "$cache" 2>/dev/null
    else
      printf '0' >"$tmp" 2>/dev/null && mv "$tmp" "$cache" 2>/dev/null
    fi
    plans="$(printf '%s' "$body" | jq -r '[.disconnected_plans[]? | select(type == "string" and test("^[a-z]+$"))] | join(" ")' 2>/dev/null)"
    printf '%s' "$plans" >"$tmp" 2>/dev/null && mv "$tmp" "$cache.plans" 2>/dev/null
    rm -f "$tmp" 2>/dev/null
  ) >/dev/null 2>&1 &
  disown 2>/dev/null || true
  # A cold cache waits briefly for its first refresh so a subject whose
  # surfaces are hidden does not see one full render before the cache exists.
  if [ ! -f "$cache" ] && [ ! -f "$cache.cold-waited" ]; then
    : >"$cache.cold-waited" 2>/dev/null
    local tries="${WEAVE_DISPLAY_SETTINGS_COLD_WAIT_TENTHS:-20}"
    while [ "$tries" -gt 0 ] && [ ! -f "$cache" ]; do
      sleep 0.1 2>/dev/null || break
      tries=$(( tries - 1 ))
    done
    [ "$(cat "$cache" 2>/dev/null)" = "1" ] && return 0
  fi
  [ "$stale_hidden" = "true" ]
}

if weave_hidden_gate </dev/null; then
  exit 0
fi

